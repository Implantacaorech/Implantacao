SELECT TECNICO,
       TO_CHAR(TURNO_INI, 'DD/MM/YYYY') AS DATA,
       TO_CHAR(INICIO_LIVRE, 'HH24:MI') AS INICIO_PERIODO_LIVRE,
       TO_CHAR(FIM_LIVRE, 'HH24:MI') AS FIM_PERIODO_LIVRE
FROM (
    SELECT TECNICO, TURNO_INI, TURNO_INI AS INICIO_LIVRE, MIN(COMP_INI) AS FIM_LIVRE
    FROM (
        SELECT G.TECNICO, G.TURNO_INI, G.TURNO_FIM, GREATEST(C.DATAINI, G.TURNO_INI) AS COMP_INI, LEAST(C.DATAFIM, G.TURNO_FIM) AS COMP_FIM
        FROM (
             SELECT T.TURNO_INI, T.TURNO_FIM, TEC.TECNICO
             FROM (
                  SELECT TO_DATE('01/01/2026 07:30:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_INI, TO_DATE('01/01/2026 11:45:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_FIM
                  FROM dual CONNECT BY LEVEL <= (SELECT ULT_MES FROM POWERBI.ULTIMO_DIA_MES WHERE MES = 12) - TO_DATE('01/01/2026', 'DD/MM/YYYY') + 1
                  UNION ALL
                  SELECT TO_DATE('01/01/2026 13:00:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_INI, TO_DATE('01/01/2026 17:30:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_FIM
                  FROM dual CONNECT BY LEVEL <= (SELECT ULT_MES FROM POWERBI.ULTIMO_DIA_MES WHERE MES = 12) - TO_DATE('01/01/2026', 'DD/MM/YYYY') + 1
             ) T
             CROSS JOIN (SELECT TECNICO FROM SICLA.TECNICOS WHERE  SETOR = 6)  TEC
             WHERE TO_CHAR(T.TURNO_INI, 'D') NOT IN ('1', '7')
               AND NOT EXISTS (SELECT 1 FROM SICLA.COMPROMISSOS F WHERE TRUNC(F.DATAINI) = TRUNC(T.TURNO_INI) AND F.ESPECIE = 3 AND F.STATUS <> 9)
        ) G
        JOIN SICLA.COMPROMISSOS C ON C.DATAINI < G.TURNO_FIM AND C.DATAFIM > G.TURNO_INI AND INSTR(C.PARTIcipantes, G.TECNICO) > 0
        WHERE C.STATUS <> 9 AND C.ESPECIE NOT IN (80, 90, 67, 3)
    ) GROUP BY TECNICO, TURNO_INI, TURNO_FIM HAVING MIN(COMP_INI) > TURNO_INI
    UNION ALL
    SELECT TECNICO, TURNO_INI, INICIO_LIVRE, FIM_LIVRE
    FROM (
        SELECT TECNICO, TURNO_INI, OCUPADO_FIM AS INICIO_LIVRE, LEAD(OCUPADO_INI) OVER (PARTITION BY TECNICO, TURNO_INI ORDER BY OCUPADO_INI) AS FIM_LIVRE
        FROM (
            SELECT G.TECNICO, G.TURNO_INI, G.TURNO_FIM, GREATEST(C.DATAINI, G.TURNO_INI) AS OCUPADO_INI, LEAST(C.DATAFIM, G.TURNO_FIM) AS OCUPADO_FIM
            FROM ( -- (Subquery de grade repetida para evitar erro de escopo)
                 SELECT T.TURNO_INI, T.TURNO_FIM, TEC.TECNICO FROM (
                    SELECT TO_DATE('01/01/2026 07:30:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_INI, TO_DATE('01/01/2026 11:45:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_FIM FROM dual CONNECT BY LEVEL <= 366
                    UNION ALL
                    SELECT TO_DATE('01/01/2026 13:00:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_INI, TO_DATE('01/01/2026 17:30:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_FIM FROM dual CONNECT BY LEVEL <= 366
                 ) T CROSS JOIN (SELECT TECNICO FROM SICLA.TECNICOS WHERE SETOR = 6) TEC -- SELECT * FROM SICLA.TECNICOS
                 WHERE TO_CHAR(T.TURNO_INI, 'D') NOT IN ('1', '7')
            ) G
            JOIN SICLA.COMPROMISSOS C ON C.DATAINI < G.TURNO_FIM AND C.DATAFIM > G.TURNO_INI AND INSTR(C.PARTIcipantes, G.TECNICO) > 0
            WHERE C.STATUS <> 9 AND C.ESPECIE NOT IN (80, 90, 67, 3)
        )
    ) WHERE FIM_LIVRE IS NOT NULL AND INICIO_LIVRE < FIM_LIVRE
    UNION ALL
    SELECT TECNICO, TURNO_INI, MAX(OCUPADO_FIM) AS INICIO_LIVRE, TURNO_FIM AS FIM_LIVRE
    FROM (
        SELECT G.TECNICO, G.TURNO_INI, G.TURNO_FIM, LEAST(C.DATAFIM, G.TURNO_FIM) AS OCUPADO_FIM
        FROM (
             SELECT T.TURNO_INI, T.TURNO_FIM, TEC.TECNICO FROM (
                SELECT TO_DATE('01/01/2026 07:30:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_INI, TO_DATE('01/01/2026 11:45:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_FIM FROM dual CONNECT BY LEVEL <= 366
                UNION ALL
                SELECT TO_DATE('01/01/2026 13:00:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_INI, TO_DATE('01/01/2026 17:30:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_FIM FROM dual CONNECT BY LEVEL <= 366
             ) T CROSS JOIN (SELECT TECNICO FROM SICLA.TECNICOS WHERE  SETOR = 6)  TEC
        ) G
        JOIN SICLA.COMPROMISSOS C ON C.DATAINI < G.TURNO_FIM AND C.DATAFIM > G.TURNO_INI AND INSTR(C.PARTIcipantes, G.TECNICO) > 0
        WHERE C.STATUS <> 9 AND C.ESPECIE NOT IN (80, 90, 67, 3)
    ) GROUP BY TECNICO, TURNO_INI, TURNO_FIM HAVING MAX(OCUPADO_FIM) < TURNO_FIM
    UNION ALL
    SELECT G.TECNICO, G.TURNO_INI, G.TURNO_INI, G.TURNO_FIM
    FROM (
         SELECT T.TURNO_INI, T.TURNO_FIM, TEC.TECNICO FROM (
            SELECT TO_DATE('01/01/2026 07:30:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_INI, TO_DATE('01/01/2026 11:45:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_FIM FROM dual CONNECT BY LEVEL <= 366
            UNION ALL
            SELECT TO_DATE('01/01/2026 13:00:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_INI, TO_DATE('01/01/2026 17:30:00', 'DD/MM/YYYY HH24:MI:SS') + LEVEL - 1 AS TURNO_FIM FROM dual CONNECT BY LEVEL <= 366
         ) T CROSS JOIN (SELECT TECNICO FROM SICLA.TECNICOS WHERE  SETOR = 6)  TEC
    ) G
    WHERE NOT EXISTS (SELECT 1 FROM SICLA.COMPROMISSOS C WHERE C.DATAINI < G.TURNO_FIM AND C.DATAFIM > G.TURNO_INI AND INSTR(C.PARTIcipantes, G.TECNICO) > 0)
)